// Hidden width grading suite for the uniseg WRG task (StringWidth).
package uniseg_test

import (
	"testing"

	uniseg "github.com/rivo/uniseg"
)

type wc = struct {
	original string
	expected int
}

func runWidth(t *testing.T, cases []wc) {
	t.Helper()
	fails := 0
	for i, c := range cases {
		if got := uniseg.StringWidth(c.original); got != c.expected {
			fails++
			if fails <= 8 {
				t.Errorf("case %d %q: StringWidth = %d, want %d", i, c.original, got, c.expected)
			}
		}
	}
	if fails > 8 {
		t.Errorf("... and %d more failing cases (of %d)", fails-8, len(cases))
	}
}

